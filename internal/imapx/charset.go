// Decode converts bytes in the given charset into an UTF-8 string. Unknown
// charsets are handled gracefully: valid UTF-8 is kept as is, otherwise
// Windows-1251 is assumed which is the most common Russian mail encoding.
func Decode(charset string, b []byte) string {
	name := normalizeCharset(charset)
	switch name {
	case "cp1251":
		return decodeTable(b, &cp1251Table)
	case "koi8r":
		return decodeTable(b, &koi8rTable)
	case "cp866":
		return decodeTable(b, &cp866Table)
	case "iso88595":
		return decodeTable(b, &iso88595Table)
	case "cp1252":
		return decodeTable(b, &cp1252Table)
	case "utf8", "usascii", "ascii", "utf7", "":
		if utf8.Valid(b) {
			return string(b)
		}
		return decodeTable(b, &cp1251Table)
	default:
		if utf8.Valid(b) {
			return string(b)
		}
		return decodeTable(b, &cp1251Table)
	}
}

func decodeTable(b []byte, table *[128]rune) string {
	var sb strings.Builder
	sb.Grow(len(b))
	for _, c := range b {
		if c < 0x80 {
			sb.WriteRune(rune(c))
			continue
		}
		r := table[c-0x80]
		if r == 0xFFFD {
			r = rune(c)
		}
		sb.WriteRune(r)
	}
	return sb.String()
}

func normalizeCharset(charset string) string {
	s := strings.ToLower(strings.TrimSpace(charset))
	s = strings.Trim(s, "\"'")
	replacer := strings.NewReplacer("-", "", "_", "", " ", "")
	s = replacer.Replace(s)
	switch s {
	case "windows1251", "win1251", "xcp1251", "cp1251", "microsoftcp1251", "1251", "cp1251ms":
		return "cp1251"
	case "koi8r", "koi8", "koi8ru", "koi8rru":
		return "koi8r"
	case "cp866", "ibm866", "866", "dos866", "x866":
		return "cp866"
	case "iso88595", "isoir144", "cyrillic", "iso88595cyrillic":
		return "iso88595"
	case "windows1252", "cp1252", "latin1", "iso88591", "windows1250", "cp1250":
		return "cp1252"
	case "utf8", "utf", "unicode11utf8", "xunicode20utf8":
		return "utf8"
	case "usascii", "ascii", "ansix341968", "iso646us":
		return "usascii"
	}
	return s
}

// charsetReader adapts Decode to mime.WordDecoder.
func charsetReader(charset string, input io.Reader) (io.Reader, error) {
	raw, err := io.ReadAll(input)
	if err != nil {
		return nil, err
	}
	return strings.NewReader(Decode(charset, raw)), nil
}

var wordDecoder = &mime.WordDecoder{CharsetReader: charsetReader}

// DecodeHeader decodes RFC 2047 encoded words ("=?utf-8?B?...?=") and raw
// 8 bit headers into readable UTF-8 text.
func DecodeHeader(s string) string {
	if s == "" {
		return ""
	}
	if decoded, err := wordDecoder.DecodeHeader(s); err == nil {
		s = decoded
	} else if !utf8.ValidString(s) {
		s = Decode("", []byte(s))
	}
	return strings.Join(strings.Fields(s), " ")
}
